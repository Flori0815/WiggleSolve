import { IDENTITY_MAT16 } from '../math/matrixHelpers';
import { beamMesh, loftMesh } from '../visual/mesh';
import type { MeshVisual, Point2, Point3 } from '../visual/mesh';
import type { ActuatorDef, BodyDef, JointDef, LoopDef, MechanismDefinition } from '../definition/schema';
import { lineSweep, rotate2, sweptFrame } from './geometry';

/**
 * Direct rotary drive at the hinge (e.g. slat track rotation, Krueger hinge).
 * For slats the "hinge" is the virtual centre of the circular tracks.
 */
export interface RotaryDrive {
  type: 'rotary';
  /** Structure fittings in the section (chord units, relative to the hinge); default: at the hinge. */
  fittings?: Point2[];
  /** Circular tracks fixed to the surface: start point and arc (rad, swept back into the wing), at span fractions. */
  tracks?: { from: Point2; arc: number; stations: number[] };
}

/**
 * Linear actuator (hydraulic cylinder): the cylinder pivots on the wing at
 * `mount`, its rod attaches to the surface at `lug`; both in the section
 * (chord units, relative to the hinge). `station` is the actuator position
 * along the hinge line (0 = root, 1 = tip).
 */
export interface LinearDrive {
  type: 'linear';
  mount: Point2;
  lug: Point2;
  station: number;
}

/**
 * A rigid surface rotating about a (swept) hinge line, e.g. spoiler, aileron,
 * flaperon, slat or Krueger flap.
 *
 * Sections are normal to the hinge line (x' aft, y up) and given in chord
 * units relative to the hinge point; the chord varies linearly from root to
 * tip.
 */
export interface HingedSurfaceParams {
  name: string;
  description: string;
  /** Hinge line in world coordinates (the hinge is assumed horizontal). */
  hingeRoot: Point3;
  hingeTip: Point3;
  chordRoot: number;
  chordTip: number;
  /** Convex section outline (counter-clockwise) in chord units relative to the hinge. */
  profile: Point2[];
  drive: RotaryDrive | LinearDrive;
  /** Deflection range [min, max] in rad; positive = trailing edge up, or down with `deployDown`. */
  deflectionRange: [number, number];
  /** Reverse the positive deflection sense (trailing edge down / nose down). */
  deployDown: boolean;
  actuatorGroup?: string;
  color: string;
  tolerance: number;
}

export const HINGED_SURFACE_DEFAULTS: Omit<HingedSurfaceParams, 'hingeRoot' | 'hingeTip' | 'chordRoot' | 'chordTip' | 'profile' | 'drive' | 'deflectionRange'> = {
  name: 'Hinged surface',
  description: '',
  deployDown: false,
  color: '#cbd5e1',
  tolerance: 1e-4,
};

/** Element ids generated by {@link hingedSurface} (prefix them when composing). */
export const SURFACE_IDS = {
  structure: 'structure',
  surface: 'surface',
  cylinder: 'cylinder',
  rod: 'rod',
  hinge: 'hinge',
  mount: 'mount',
  cylinderAxis: 'cylinder_axis',
  rodEnd: 'rod_end',
  lug: 'lug',
  actuator: 'actuator',
  hingeJoint: 'hinge_rot',
  cylinderJoint: 'cylinder_rot',
} as const;

const ids = SURFACE_IDS;
const body = (id: string, nodes: BodyDef['nodes'], visuals: MeshVisual[]): BodyDef =>
  ({ id, transform: [...IDENTITY_MAT16], nodes, visuals });

/**
 * Actuator stroke range (length units) for the deflection range, sampled;
 * throws when the actuator would pass a toggle position.
 */
function strokeRange(drive: LinearDrive, [lo, hi]: [number, number], sense: number, chord: number): [number, number] {
  const length = (angle: number) => {
    const lug = rotate2(drive.lug, sense * angle);
    return chord * Math.hypot(lug[0] - drive.mount[0], lug[1] - drive.mount[1]);
  };
  const l0 = length(0);
  const samples = Array.from({ length: 41 }, (_, i) => length(lo + (hi - lo) * i / 40) - l0);
  const increasing = samples[40] > samples[0];
  for (let i = 1; i < samples.length; i++) {
    if ((samples[i] > samples[i - 1]) !== increasing) throw new Error('Invalid hinged surface: actuator passes a toggle position within the deflection range');
  }
  return [Math.min(samples[0], samples[40]), Math.max(samples[0], samples[40])];
}

/** Generates a hinged surface with its drive as a complete mechanism definition. */
export function hingedSurface(params: Partial<HingedSurfaceParams> & Pick<HingedSurfaceParams, 'hingeRoot' | 'hingeTip' | 'chordRoot' | 'chordTip' | 'profile' | 'drive' | 'deflectionRange'>): MechanismDefinition {
  const p: HingedSurfaceParams = { ...HINGED_SURFACE_DEFAULTS, ...params };
  const { sweep, length } = lineSweep(p.hingeRoot, p.hingeTip);
  if (!(length > 0)) throw new Error('Invalid hinged surface: hinge line has zero length');
  const frame = sweptFrame(sweep, p.hingeRoot);
  const chord = (z: number) => p.chordRoot + (p.chordTip - p.chordRoot) * z / length;
  const point = (q: Point2, z: number): Point3 => frame.toWorld([q[0] * chord(z), q[1] * chord(z), z]);
  const section = (z: number) => p.profile.map(q => point(q, z));
  const flip = p.deployDown;
  const node = (id: string, q: Point2, z: number, angle = 0) => ({ id, localTransform: frame.matrix(point(q, z), angle, flip) });
  const group = p.actuatorGroup ? { group: p.actuatorGroup } : {};

  const panel = loftMesh(section(0), section(length), { color: p.color });
  const hingeNodes = [node(ids.hinge, [0, 0], 0)];
  /** Small fitting block on the structure at a section point, for representation. */
  const fitting = (q: Point2, z: number): MeshVisual => {
    const h = 0.03;
    const dz = h * chord(z);
    const square: Point2[] = [[q[0] - h, q[1] - h], [q[0] + h, q[1] - h], [q[0] + h, q[1] + h], [q[0] - h, q[1] + h]];
    return loftMesh(square.map(r => point(r, z - dz)), square.map(r => point(r, z + dz)), { color: '#64748b' });
  };

  if (p.drive.type === 'rotary') {
    const { fittings = [[0, 0]], tracks } = p.drive;
    const stations = [0, length];
    const trackMeshes = (tracks?.stations ?? []).flatMap(f => {
      const z = f * length;
      const arc = Array.from({ length: 5 }, (_, i) => rotate2(tracks!.from, -(flip ? -1 : 1) * tracks!.arc * i / 4));
      return arc.slice(1).map((q, i) => beamMesh(point(arc[i], z), point(q, z), 0.015 * chord(z), 0.03 * chord(z), { color: '#94a3b8' }));
    });
    return {
      name: p.name,
      description: p.description,
      system: {
        bodies: [
          body(ids.structure, hingeNodes, stations.flatMap(z => fittings.map(q => fitting(q, z)))),
          body(ids.surface, [], [panel, ...trackMeshes]),
        ],
        globalNodes: [],
        joints: [{ id: ids.actuator, type: 'revolute', axis: [0, 0, 1], limits: [...p.deflectionRange] }],
      },
      actuators: [{ id: ids.actuator, type: 'revolute', axis: 'z', pivotNode: ids.hinge, movingBodies: [ids.surface], ...group }],
      sequence: [],
    };
  }

  const drive = p.drive;
  const z = drive.station * length;
  const c = chord(z);
  const stroke = strokeRange(drive, p.deflectionRange, flip ? -1 : 1, c);
  const direction = Math.atan2(drive.lug[1] - drive.mount[1], drive.lug[0] - drive.mount[0]);
  const mid: Point2 = [(drive.mount[0] + drive.lug[0]) / 2, (drive.mount[1] + drive.lug[1]) / 2];
  const width = 0.06 * c;
  const actuators: ActuatorDef[] = [{ id: ids.actuator, type: 'prismatic', axis: 'x', pivotNode: ids.cylinderAxis, movingBodies: [ids.rod], ...group }];
  const joints: JointDef[] = [
    { id: ids.actuator, type: 'prismatic', axis: [1, 0, 0], limits: stroke },
    { id: ids.cylinderJoint, type: 'revolute', axis: [0, 0, 1], limits: [-Math.PI, Math.PI] },
    { id: ids.hingeJoint, type: 'revolute', axis: [0, 0, 1], limits: [p.deflectionRange[0] - 0.1, p.deflectionRange[1] + 0.1] },
  ];
  const pairs: Array<[string, string]> = [[ids.rodEnd, ids.lug]];
  const sequence: LoopDef[] = [{
    type: 'loop',
    max_iterations: 50,
    condition: { type: 'distance_less_than', nodeA: ids.rodEnd, nodeB: ids.lug, threshold: p.tolerance },
    steps: [{
      type: 'operation',
      operation: {
        type: 'close_loops',
        joints: [
          { jointId: ids.cylinderJoint, pivotNode: ids.mount, movingBodies: [ids.cylinder, ids.rod] },
          { jointId: ids.hingeJoint, pivotNode: ids.hinge, movingBodies: [ids.surface] },
        ],
        pairs,
      },
    }],
  }];

  return {
    name: p.name,
    description: p.description,
    system: {
      bodies: [
        body(ids.structure, [...hingeNodes, node(ids.mount, drive.mount, z)], [fitting([0, 0], z), fitting(drive.mount, z)]),
        body(ids.cylinder, [{ id: ids.cylinderAxis, localTransform: frame.matrix(point(drive.mount, z), direction) }],
          [beamMesh(point(drive.mount, z), point(mid, z), width, width, { color: '#f59e0b' })]),
        body(ids.rod, [node(ids.rodEnd, drive.lug, z)], [beamMesh(point(mid, z), point(drive.lug, z), width / 2, width / 2, { color: '#fbbf24' })]),
        body(ids.surface, [node(ids.lug, drive.lug, z)], [panel]),
      ],
      globalNodes: [],
      joints,
    },
    actuators,
    sequence,
  };
}
